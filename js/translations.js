/**
 * Helper to convert digits to Bengali if requested
 */
function toBengaliDigits(input) {
  if (input === null || input === undefined) return '';
  const str = String(input);
  const bengaliNumbers = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];
  return str.replace(/[0-9]/g, (w) => bengaliNumbers[parseInt(w, 10)]);
}

/**
 * Global translation retriever
 */
function t(key, lang = 'en') {
  const currentLang = lang || localStorage.getItem('nexvora_lang') || 'en';
  const dict = NexVoraTranslations[currentLang] || NexVoraTranslations.en;
  return dict[key] !== undefined ? dict[key] : (NexVoraTranslations.en[key] || key);
}
